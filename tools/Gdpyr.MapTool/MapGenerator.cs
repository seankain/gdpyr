using System;
using System.Collections.Generic;
using Gdpyr.Sim.Level;
using Godot;

namespace Gdpyr.MapTool;

/// <summary>
/// A seeded map (docs/LEVEL_EDITOR.md §11, LE2): rolling hills, and the pieces a
/// round needs, each placed through <see cref="PrefabPlacement"/> on the pad it makes.
/// The first maps are this one's — LE3 bundles one — so it is compiled into the tests
/// as well, which hold that every seed they try passes the validator and reads back
/// from its file as it was written.
///
/// The layout is MAPS.md §2.3's: the spawn line and locker in the south-west, the
/// barracks in the north-east with its door to the south, a node in the middle and
/// the anchor between. Two more nodes, the cover round the nodes and a bunker are
/// where the seed puts them. A piece's ground is made level before it is placed — a
/// disc at the ground's mean, with a 20° skirt — so that no seed's hills refuse it;
/// what the generator cannot place of the optional pieces it leaves out.
///
/// The same seed, name and time give the same document, and in one build the same
/// bytes: the hills are integer-seeded and every height is rounded to a step.
/// </summary>
public static class MapGenerator
{
	/// <summary>The hills' height at the coarsest lattice [m]: gentler than §10's, whose steepest face is 59.6° (§13).</summary>
	public const float DefaultHillMeters = 5f;

	private static readonly int[] Lattices = { 3, 6, 12, 24 };

	public static MapDocument Generate(int seed, string name = null, long unixSeconds = 0, string author = "",
		float hillMeters = DefaultHillMeters)
	{
		var random = new Random(seed);
		var guid = new byte[16];
		random.NextBytes(guid);
		guid[7] = (byte)((guid[7] & 0x0F) | 0x40);
		guid[8] = (byte)((guid[8] & 0x3F) | 0x80);

		MapDocument document = MapDocument.Create(new Guid(guid), name ?? $"generated-{seed}", unixSeconds);
		document.Author = author ?? string.Empty;
		document.Description = $"Generated by gdpyr-map from seed {seed}.";
		HeightField field = document.Terrain;
		Hills(field, random, hillMeters);
		field.Round(field.Bounds);

		Vector2[] nodes = NodeSites(random);
		Site(document, new Vector2(-78f, 88f), 34f);
		Site(document, new Vector2(84f, -80f), 24f);
		foreach (Vector2 node in nodes)
		{
			Site(document, node, 13f);
		}

		Place(document, PrefabSpecs.Barracks, 90f, -90f, MathF.PI);
		Place(document, PrefabSpecs.SpawnLine, -90f, 90f, 0f);
		Place(document, PrefabSpecs.WeaponLocker, -90f, 96f, MathF.PI);
		Place(document, PrefabSpecs.VehicleKiosk, -62f, 92f, MathF.PI);
		for (int i = 0; i < nodes.Length; i++)
		{
			MapParameter[] perk = i == nodes.Length - 1
				? new[] { new MapParameter(PrefabSpecs.NodePerkKey, (int)Gdpyr.Sim.NodePerk.Drone) }
				: null;
			Place(document, PrefabSpecs.ResourceNode, nodes[i].X, nodes[i].Y, 0f, perk);
		}

		Place(document, PrefabSpecs.StrategistAnchor, 45f, -45f, 0f);
		Place(document, PrefabSpecs.HeavyGun, -80f, 75f, MathF.PI);
		Place(document, PrefabSpecs.MortarLauncher, -100f, 75f, MathF.PI);
		Place(document, PrefabSpecs.AmmoCan, -86f, 96f, 0f);
		Place(document, PrefabSpecs.AmmoCan, -94f, 96f, 0f);
		Place(document, PrefabSpecs.StructurePillbox, 78f, -66f, MathF.PI);
		Place(document, PrefabSpecs.StructureSandbagWall, 70f, -76f, MathF.PI * 0.5f);

		foreach (Vector2 node in nodes)
		{
			for (int i = 0; i < 6; i++)
			{
				ushort cover = i < 4 ? PrefabSpecs.CoverLowWall : PrefabSpecs.CoverBlock;
				TryPlaceNear(document, random, cover, node, 12f, 24f);
			}
		}

		TryPlaceNear(document, random, PrefabSpecs.Bunker, new Vector2(30f, 60f), 0f, 30f);
		return document;
	}

	/// <summary>Value-noise fBm, as LevelGround and design_checks.py make it, lifted so its lows are over the water.</summary>
	private static void Hills(HeightField field, Random random, float amplitude)
	{
		int n = field.Width;
		double amp = amplitude;
		foreach (int cells in Lattices)
		{
			var lattice = new double[(cells + 2) * (cells + 2)];
			for (int i = 0; i < lattice.Length; i++)
			{
				lattice[i] = (random.NextDouble() * 2d) - 1d;
			}

			for (int z = 0; z < field.Depth; z++)
			{
				double fz = z * (double)cells / n;
				int lz = (int)fz;
				double sz = Smooth(fz - lz);
				for (int x = 0; x < n; x++)
				{
					double fx = x * (double)cells / n;
					int lx = (int)fx;
					double sx = Smooth(fx - lx);
					int i = (lz * (cells + 2)) + lx;
					double near = Lerp(lattice[i], lattice[i + 1], sx);
					double far = Lerp(lattice[i + cells + 2], lattice[i + cells + 3], sx);
					field[x, z] += (float)(amp * Lerp(near, far, sz));
				}
			}

			amp *= 0.5d;
		}

		for (int i = 0; i < field.Heights.Length; i++)
		{
			field.Heights[i] += amplitude * 0.8f;
		}
	}

	/// <summary>
	/// Where the nodes go: one in the middle, and two the seed puts, each outside the
	/// barracks' ring with room to spare, away from the spawn and from each other.
	/// </summary>
	private static Vector2[] NodeSites(Random random)
	{
		var sites = new List<Vector2> { Vector2.Zero };
		var barracks = new Vector2(90f, -90f);
		var spawn = new Vector2(-80f, 88f);
		for (int tries = 0; sites.Count < 3 && tries < 10_000; tries++)
		{
			var candidate = new Vector2((float)((random.NextDouble() * 180d) - 90d), (float)((random.NextDouble() * 180d) - 90d));
			if (candidate.DistanceTo(barracks) < PrefabSpecs.BarracksDefendedRadiusMeters + 12f
				|| candidate.DistanceTo(spawn) < 50f)
			{
				continue;
			}

			bool apart = true;
			foreach (Vector2 site in sites)
			{
				apart &= candidate.DistanceTo(site) >= 45f;
			}

			if (apart)
			{
				sites.Add(candidate);
			}
		}

		return sites.ToArray();
	}

	/// <summary>
	/// Makes a disc of ground level for the pieces about to stand on it, at a level a
	/// pad would choose for itself (<see cref="PrefabPlacement.PadLevelSample"/> of its
	/// own height), so that the pads made on it move nothing, and over the water.
	/// </summary>
	private static void Site(MapDocument document, Vector2 centre, float radius)
	{
		HeightField field = document.Terrain;
		PadArea disc = PadArea.Disc(centre.X, centre.Y, radius);
		PrefabPlacement.Fit(field, disc, out _, out _, out float mean, out _);
		float level = MathF.Max(mean, document.Bands.WaterLevelMeters + 1f);
		level = HeightField.ToMeters(PrefabPlacement.PadLevelSample(Gdpyr.Sim.Quantize.MetersToI16(level)));
		SampleRect touched = TerrainConform.Disc(field, centre.X, centre.Y, radius, level, 0f, HeightField.Grade(20f));
		field.Round(touched);
	}

	private static void Place(MapDocument document, ushort prefab, float x, float z, float yaw,
		MapParameter[] parameters = null)
	{
		PlacementCheck check = PrefabPlacement.Check(document, new PlacementRequest(prefab, x, z, yaw, 0f, parameters));
		if (!check.IsOk)
		{
			throw new InvalidOperationException(
				$"the generator could not place {PrefabSpecs.Get(prefab).Name} at ({x}, {z}): {check}");
		}

		check.Edit.Apply(document);
	}

	/// <summary>Tries a prefab at up to 40 places the seed picks round a point, turned in 15° steps; places it at the first that takes it.</summary>
	private static bool TryPlaceNear(MapDocument document, Random random, ushort prefab, Vector2 centre, float near,
		float far)
	{
		for (int tries = 0; tries < 40; tries++)
		{
			float angle = (float)(random.NextDouble() * Math.PI * 2d);
			float distance = near + (float)(random.NextDouble() * (far - near));
			float yaw = random.Next(24) * (MathF.PI / 12f);
			var request = new PlacementRequest(prefab, centre.X + (MathF.Cos(angle) * distance),
				centre.Y + (MathF.Sin(angle) * distance), yaw);
			PlacementCheck check = PrefabPlacement.Check(document, request);
			if (check.IsOk)
			{
				check.Edit.Apply(document);
				return true;
			}
		}

		return false;
	}

	private static double Smooth(double t) => t * t * (3d - (2d * t));

	private static double Lerp(double a, double b, double t) => a + ((b - a) * t);
}
